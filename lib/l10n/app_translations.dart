  static String formatNumber(int number, String langCode) {
    return formatStringNumber(number.toString(), langCode);
  }

  static String formatStringNumber(String input, String langCode) {
    if (langCode == 'en') return input;
    
    const List<String> hiDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
    const List<String> guDigits = ['૦', '૧', '૨', '૩', '૪', '૫', '૬', '૭', '૮', '૯'];
    
    final targetDigits = langCode == 'hi' ? hiDigits : guDigits;
    
    String result = '';
    for (int i = 0; i < input.length; i++) {
      int? num = int.tryParse(input[i]);
      if (num != null) {
        result += targetDigits[num];
      } else {
        result += input[i];
      }
    }
    return result;
  }
